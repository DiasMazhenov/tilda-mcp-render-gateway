import test from 'node:test';
import assert from 'node:assert/strict';
import {spawn} from 'node:child_process';
import {mkdtemp,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {createHash} from 'node:crypto';
import {authUtils} from '../src/auth.mjs';
const dir=await mkdtemp(join(tmpdir(),'tilda-settings-'));
const origin='https://example.onrender.com',local='http://127.0.0.1:39833';
const app=spawn(process.execPath,['src/server.mjs'],{cwd:new URL('..',import.meta.url).pathname,env:{...process.env,PORT:'39833',PUBLIC_BASE_URL:origin,ADMIN_PASSWORD:'TestPass10',OAUTH_SIGNING_SECRET:'a'.repeat(64),DATA_DIR:dir},stdio:'ignore'});
test.after(async()=>{app.kill();await new Promise(r=>app.once('exit',r));await rm(dir,{recursive:true,force:true});});
for(let i=0;i<100;i++){try{if((await fetch(local+'/healthz')).ok)break;}catch{}await new Promise(r=>setTimeout(r,50));}
const csrfFrom=html=>html.match(/name="csrf" value="([^"]+)"/)?.[1];
test('password-protected settings manage named keys without revealing saved credentials',async()=>{
 const page=await fetch(local+'/settings');
 let html=await page.text();
 assert.match(html,/name="password"/);
 const login=await fetch(local+'/settings/login',{method:'POST',redirect:'manual',headers:{origin,'content-type':'application/x-www-form-urlencoded',cookie:page.headers.get('set-cookie').split(';')[0]},body:new URLSearchParams({csrf:csrfFrom(html),password:'TestPass10'})});
 assert.equal(login.status,303);
 const cookie=login.headers.get('set-cookie').split(';')[0];
 const settings=await fetch(local+'/settings',{headers:{cookie}});
 html=await settings.text();
 assert.match(html,/Добавить подключение/);
 const csrf=csrfFrom(html);
 const add=await fetch(local+'/settings/add',{method:'POST',redirect:'manual',headers:{origin,cookie,'content-type':'application/x-www-form-urlencoded'},body:new URLSearchParams({csrf,name:'<Наш проект>',token:'HIDDEN_TOKEN'})});
 assert.equal(add.status,303);
 html=await (await fetch(local+'/settings',{headers:{cookie}})).text();
 assert.ok(html.includes('&lt;Наш проект&gt;'));
 assert.ok(!html.includes('HIDDEN_TOKEN'));
 const id=html.match(/name="id" value="([^"]+)"/)?.[1];
 let version=html.match(/name="version" value="([^"]+)"/)?.[1];
 assert.ok(id&&version);
 const reg=await (await fetch(local+'/register',{method:'POST',body:JSON.stringify({redirect_uris:['https://chatgpt.com/connector_platform_oauth_redirect']})})).json();
 const verifier='test-verifier'.repeat(5);
 const request={client_id:reg.client_id,redirect_uri:'https://chatgpt.com/connector_platform_oauth_redirect',response_type:'code',code_challenge:createHash('sha256').update(verifier).digest('base64url'),code_challenge_method:'S256',resource:origin+'/mcp/tilda'};
 const oauthPage=await fetch(local+'/authorize?'+new URLSearchParams(request));
 const oauthHtml=await oauthPage.text();
 assert.match(oauthHtml,/Управление сохранёнными подключениями/);
 const oauthLogin=await fetch(local+'/authorize',{method:'POST',redirect:'manual',headers:{origin},body:new URLSearchParams({...request,csrf:csrfFrom(oauthHtml),password:'TestPass10'})});
 assert.equal(oauthLogin.status,302);
 const oauthCode=new URL(oauthLogin.headers.get('location')).searchParams.get('code');
 const tokens=await (await fetch(local+'/token',{method:'POST',body:new URLSearchParams({grant_type:'authorization_code',code:oauthCode,client_id:reg.client_id,redirect_uri:request.redirect_uri,code_verifier:verifier,resource:request.resource})})).json();
 const claim=authUtils('a'.repeat(64)).decrypt(tokens.access_token);
 assert.equal(claim.registry,true);
 assert.equal(claim.tildaToken,undefined);
 const mcp=message=>fetch(local+'/mcp/tilda',{method:'POST',headers:{authorization:'Bearer '+tokens.access_token},body:JSON.stringify({jsonrpc:'2.0',id:1,...message})});
 const initialized=await (await mcp({method:'initialize',params:{protocolVersion:'2025-11-25'}})).json();
 assert.equal(initialized.result.serverInfo.name,'tilda-named-gateway');
 const list=await (await mcp({method:'tools/call',params:{name:'list_connections',arguments:{}}})).json();
 assert.equal(JSON.parse(list.result.content[0].text).connections[0].id,id);
 assert.ok(!JSON.stringify(list).includes('HIDDEN_TOKEN'));
 const noSelection=await (await mcp({method:'tools/call',params:{name:'call_tilda_tool',arguments:{tool_name:'read_pages',arguments:{}}}})).json();
 assert.equal(noSelection.result.isError,true);
 const updated=await fetch(local+'/settings/update',{method:'POST',redirect:'manual',headers:{origin,cookie},body:new URLSearchParams({csrf,id,version,name:'Переименован',token:'UPDATED_TOKEN'})});
 assert.equal(updated.status,303);
 html=await (await fetch(local+'/settings',{headers:{cookie}})).text();
 assert.ok(html.includes('Переименован'));
 assert.ok(!html.includes('UPDATED_TOKEN'));
 version=html.match(/name="version" value="([^"]+)"/)?.[1];
 const foreign=await fetch(local+'/settings/delete',{method:'POST',headers:{origin:'https://evil.example',cookie},body:new URLSearchParams({csrf,id,version,confirm_delete:'yes'})});
 assert.equal(foreign.status,403);
 const noCsrf=await fetch(local+'/settings/delete',{method:'POST',headers:{origin,cookie},body:new URLSearchParams({id,version})});
 assert.equal(noCsrf.status,403);
 const removed=await fetch(local+'/settings/delete',{method:'POST',redirect:'manual',headers:{origin,cookie},body:new URLSearchParams({csrf,id,version,confirm_delete:'yes'})});
 assert.equal(removed.status,303);
 html=await (await fetch(local+'/settings',{headers:{cookie}})).text();
 assert.ok(!html.includes('Переименован'));
 const afterDelete=await (await mcp({method:'tools/call',params:{name:'list_connections',arguments:{}}})).json();
 assert.equal(JSON.parse(afterDelete.result.content[0].text).connections.length,0);
 const anonymous=await fetch(local+'/settings/add',{method:'POST',redirect:'manual',headers:{origin},body:new URLSearchParams({name:'Bad',token:'SECRET'})});
 assert.equal(anonymous.status,401);
});
